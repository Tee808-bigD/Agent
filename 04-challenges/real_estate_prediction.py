# Import necessary libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split, cross_val_score, GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression, Ridge, Lasso
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor
from sklearn.metrics import mean_squared_error, r2_score, mean_absolute_error
import joblib
import warnings
warnings.filterwarnings('ignore')

# Set display options
pd.set_option('display.max_columns', None)
pd.set_option('display.float_format', '{:.3f}'.format)

# Load the dataset
url = 'https://raw.githubusercontent.com/MicrosoftDocs/ml-basics/refs/heads/master/challenges/data/real_estate.csv'
data = pd.read_csv(url)

print("="*60)
print("REAL ESTATE PRICE PREDICTION CHALLENGE")
print("="*60)
print(f"\nDataset shape: {data.shape}")
print("\nFirst 5 rows:")
print(data.head())

"""# **1. EXPLORATORY DATA ANALYSIS**"""

# 1. EXPLORATORY DATA ANALYSIS
print("\n" + "="*60)
print("DATA EXPLORATION")
print("="*60)

# Check data types and missing values
print("\nData Info:")
print(data.info())

print("\nMissing Values:")
print(data.isnull().sum())

print("\nBasic Statistics:")
print(data.describe())

# Check for duplicates
print(f"\nDuplicate rows: {data.duplicated().sum()}")

"""# **2. VISUALIZE DATA DISTRIBUTIONS**"""

# 2. VISUALIZE DATA DISTRIBUTIONS
fig, axes = plt.subplots(2, 3, figsize=(15, 10))

# Target variable distribution
axes[0, 0].hist(data['price_per_unit'], bins=30, edgecolor='black', alpha=0.7)
