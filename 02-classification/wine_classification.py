axes[1].set_xlabel('False Positive Rate')
axes[1].set_ylabel('True Positive Rate')
axes[1].set_title('ROC Curves (One-vs-Rest)')
axes[1].legend(loc="lower right")

plt.tight_layout()
plt.show()

# Calculate per-class metrics
print("\nPer-Class Performance:")
for i, variety in enumerate(['Variety A', 'Variety B', 'Variety C']):
    precision = precision_score(y_test == i, y_test_pred == i)
    recall = recall_score(y_test == i, y_test_pred == i)
    f1 = f1_score(y_test == i, y_test_pred == i)
    print(f"  {variety}: Precision={precision:.4f}, Recall={recall:.4f}, F1={f1:.4f}")

